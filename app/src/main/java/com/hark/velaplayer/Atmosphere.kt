/**
 * v2.12 atmosphere: the deep "Midnight Glass" backdrop behind every screen.
 *
 * A vertical gradient (darker top → mid → softly tinted bottom) plus two large radial glows (one low on the left,
 * one high on the right) in the theme's own colours, and a faint static grain so the dark gradient never bands.
 * Each preset defines its colours (atmoTop/Mid/Bottom/GlowA/GlowB, generated by tools/themegen/Gen.java); custom
 * themes derive them from their one picked colour ([fromSeed]).
 *
 * Cost: three shaders + one tiled 96 px grain bitmap, drawn as the window background (cached by the renderer).
 * It is never used inside list items and never animates.
 */
object Atmosphere {
    data class Atmo(val top: Int, val mid: Int, val bottom: Int, val glowA: Int, val glowB: Int, val dark: Boolean)

    private val attrs = intArrayOf(R.attr.atmoTop, R.attr.atmoMid, R.attr.atmoBottom, R.attr.atmoGlowA, R.attr.atmoGlowB)

    /** The atmosphere of the theme this context is drawn with (custom themes: generated from their colour). */
    fun of(c: Context): Atmo {
        val dark = !isLightContext(c)
        val sel = ThemeManager.selection(c)
        if (sel.isCustom) return fromSeed(sel.seed, sel.secondary, dark)
        val v = attrs.map { ThemeManager.attrOr(c, it, 0) }
        if (v[0] == 0 && v[1] == 0) return fromSeed(ThemeManager.primary(c), 0, dark)
        return Atmo(v[0], v[1], v[2], v[3], v[4], dark)
    }

    private fun isLightContext(c: Context): Boolean {
        val tv = android.util.TypedValue()
        if (c.theme.resolveAttribute(androidx.appcompat.R.attr.isLightTheme, tv, true)) return tv.data != 0
        val night = c.resources.configuration.uiMode and android.content.res.Configuration.UI_MODE_NIGHT_MASK
        return night != android.content.res.Configuration.UI_MODE_NIGHT_YES
    }

    fun mix(a: Int, b: Int, f: Float): Int {
        val t = f.coerceIn(0f, 1f)
        return Color.rgb(
            (Color.red(a) * (1 - t) + Color.red(b) * t).toInt(),
            (Color.green(a) * (1 - t) + Color.green(b) * t).toInt(),
            (Color.blue(a) * (1 - t) + Color.blue(b) * t).toInt())
    }
    fun alpha(c: Int, a: Int) = (a shl 24) or (c and 0xFFFFFF)

    /** Same recipe as Gen.java's glassRoles, from one colour: a deep tint of its hue plus glows of it and a neighbour hue. */
    fun fromSeed(seed: Int, secondary: Int, dark: Boolean): Atmo {
        val hsv = FloatArray(3); Color.colorToHSV(seed, hsv)
        val tint = Color.HSVToColor(floatArrayOf(hsv[0], (hsv[1] * 0.9f).coerceAtMost(0.75f), 0.5f))
        val glowA = seed or 0xFF000000.toInt()
        val glowB = if (secondary != 0) secondary or 0xFF000000.toInt()
            else Color.HSVToColor(floatArrayOf((hsv[0] + 38f) % 360f, hsv[1], (hsv[2] * 0.8f).coerceAtLeast(0.35f)))
        return if (dark) Atmo(mix(0xFF020308.toInt(), tint, 0.10f), mix(0xFF060812.toInt(), tint, 0.22f), mix(0xFF0C0F1E.toInt(), tint, 0.42f),
            alpha(glowA, 0x5C), alpha(glowB, 0x3D), true)
        else Atmo(mix(0xFFF5F7FB.toInt(), tint, 0.04f), mix(0xFFEAEEF5.toInt(), tint, 0.06f), mix(0xFFDBE2EE.toInt(), tint, 0.10f),
            alpha(mix(glowA, -1, 0.35f), 0x3D), alpha(mix(glowB, -1, 0.40f), 0x33), false)
    }

    /**
     * Puts the atmosphere behind the whole window and lets it show through the status bar (and, in dark mode, tints
     * the navigation bar to its bottom colour). Called by [ThemedActivity] for every non-player screen.
     */
    @Suppress("DEPRECATION")
    fun applyTo(a: Activity) {
        val w = a.window ?: return
        val atmo = of(a)
        w.setBackgroundDrawable(backdrop(a, atmo))
        if (atmo.dark || Build.VERSION.SDK_INT >= 23) w.statusBarColor = android.graphics.Color.TRANSPARENT
        if (atmo.dark) w.navigationBarColor = atmo.bottom
        else if (Build.VERSION.SDK_INT >= 27) {
            w.navigationBarColor = atmo.bottom
            androidx.core.view.WindowCompat.getInsetsController(w, w.decorView).isAppearanceLightNavigationBars = true
        }
    }

    /**
     * A copy of the window atmosphere for an opaque view that must hide what is under it while it animates (settings
     * screens). It lines itself up with the window so its gradient continues the backdrop seamlessly.
     */
    fun viewBackground(v: View): Drawable {
        val d = backdrop(v.context, of(v.context))
        v.background = d
        v.post {
            val loc = IntArray(2); v.getLocationInWindow(loc)
            when (d) { is AtmosphereDrawable -> d.align(loc[1], v.rootView.height); is BackdropDrawable -> d.align(loc[1], v.rootView.height) }
        }
        return d
    }

    /** v2.18: the user's background photo ([Backdrop]) when one is set, otherwise the theme atmosphere. */
    fun backdrop(c: Context, atmo: Atmo = of(c)): Drawable {
        val p = Backdrop.processed(c) ?: return AtmosphereDrawable(atmo)
        return BackdropDrawable(c, atmo, p, Backdrop.spec(c))
    }
}

class AtmosphereDrawable(private val atmo: Atmosphere.Atmo) : Drawable() {
    private val base = Paint(Paint.DITHER_FLAG)
    private val glowA = Paint(Paint.DITHER_FLAG or Paint.ANTI_ALIAS_FLAG)
    private val glowB = Paint(Paint.DITHER_FLAG or Paint.ANTI_ALIAS_FLAG)
    private val grain = Paint().apply { shader = BitmapShader(grainBitmap, Shader.TileMode.REPEAT, Shader.TileMode.REPEAT) }
    private var offsetY = 0
    private var frameH = 0
    private val m = Matrix()

    /** Treat this drawable as a window-sized backdrop seen from [offset] px below the window top. */
    fun align(offset: Int, windowHeight: Int) { offsetY = offset; frameH = windowHeight; onBoundsChange(bounds); invalidateSelf() }

    override fun onBoundsChange(b: Rect) {
        val w = b.width().toFloat().coerceAtLeast(1f)
        val h = (if (frameH > 0) frameH else b.height()).toFloat().coerceAtLeast(1f)
        val oy = -offsetY.toFloat()
        base.shader = LinearGradient(0f, oy, 0f, oy + h, intArrayOf(atmo.top, atmo.mid, atmo.bottom), floatArrayOf(0f, 0.42f, 1f), Shader.TileMode.CLAMP)
        val r = max(w, h)
        glowA.shader = RadialGradient(w * 0.12f, oy + h * 0.86f, r * 0.75f,
            intArrayOf(atmo.glowA, Atmosphere.alpha(atmo.glowA, (Color.alpha(atmo.glowA) * 0.35f).toInt()), atmo.glowA and 0xFFFFFF),
            floatArrayOf(0f, 0.5f, 1f), Shader.TileMode.CLAMP)
        glowB.shader = RadialGradient(w * 0.92f, oy + h * 0.10f, r * 0.55f,
            intArrayOf(atmo.glowB, Atmosphere.alpha(atmo.glowB, (Color.alpha(atmo.glowB) * 0.3f).toInt()), atmo.glowB and 0xFFFFFF),
            floatArrayOf(0f, 0.55f, 1f), Shader.TileMode.CLAMP)
    }

    override fun draw(c: Canvas) {
        val b = bounds
        c.drawRect(b, base)
        c.drawRect(b, glowA)
        c.drawRect(b, glowB)
        c.drawRect(b, grain)
    }

    override fun setAlpha(alpha: Int) { base.alpha = alpha; glowA.alpha = alpha; glowB.alpha = alpha }
    override fun setColorFilter(cf: ColorFilter?) { base.colorFilter = cf }
    @Deprecated("Deprecated in Java") override fun getOpacity() = PixelFormat.OPAQUE

    companion object {
        /** 96×96 static grain: ±1–2 levels of light/dark noise, enough to break 8-bit gradient bands, invisible otherwise. */
        val grainBitmap: Bitmap by lazy {
            val n = 96
            val px = IntArray(n * n)
            val rnd = Random(7)
            for (i in px.indices) {
                val v = rnd.nextInt(0, 100)
                px[i] = when {
                    v < 30 -> 0x06FFFFFF
                    v < 60 -> 0x07000000
                    else -> 0
                }
            }
            Bitmap.createBitmap(px, n, n, Bitmap.Config.ARGB_8888)
        }
    }
}
