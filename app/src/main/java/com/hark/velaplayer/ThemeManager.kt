/**
 * One place for the app's colors. Every screen asks this object for its accent, so a change in the
 * Theme editor reaches buttons, switches, sliders, chips, progress bars and highlights everywhere.
 *
 * - Presets: hand-tuned Material 3 palettes (light + dark) generated from each seed color.
 * - Custom colors: Android 12+ builds a full Material 3 palette from the exact color picked.
 *   Android 11 and older can't build palettes at runtime, so the closest preset palette is used.
 */
object ThemeManager {
    /**
     * One ready-made theme: full palette (background, surfaces, glass tint/stroke, primary, secondary, tertiary,
     * text) in light and dark, plus the always-dark player variant. Generated by tools/themegen/Gen.java into
     * values(-night)/accents(_player).xml and [ThemeCatalog].
     * - [style]/[playerStyle]: everything. [glassStyle]/[glassPlayerStyle]: background, surfaces, text and glass only.
     * - [secondStyle]/[secondPlayerStyle]: secondary + tertiary accents only (used by custom themes' Advanced options).
     */
    data class Preset(
        val key: String, val label: String, val section: String, val seed: Int,
        val style: Int, val playerStyle: Int, val glassStyle: Int, val glassPlayerStyle: Int,
        val secondStyle: Int, val secondPlayerStyle: Int,
    )

    val presets: List<Preset> get() = ThemeCatalog.all

    const val DEFAULT_KEY = "midnight_glass"
    /** Seed of the default theme (v2.12: Midnight Glass; v2.11: Pure Black Glass; before: Vela Violet). */
    val DEFAULT_SEED: Int get() = presetByKey(DEFAULT_KEY)?.seed ?: 0xFF8FA8FF.toInt()

    /**
     * v2.12: v2.11 (and older) preset keys → the nearest v2.12 preset, so a theme the user picked survives the
     * new catalogue. Installs that never picked a theme have no theme_key/accent_seed and get Midnight Glass.
     */
    val LEGACY: Map<String, String> = mapOf(
        "pure_black" to "obsidian_noir", "midnight" to "sapphire_depths", "nebula" to "violet_nebula",
        "crimson" to "crimson_eclipse", "slate" to "arctic_silver", "aurora" to "aurora_glass",
        "violet" to "amethyst_night", "ocean" to "sapphire_depths", "ruby" to "ruby_noir", "indigo" to "royal_indigo",
        "cyan" to "cyber_cyan", "emerald" to "emerald_aura", "sunset" to "sunset_ember", "amber" to "golden_eclipse",
        "rose_gold" to "rose_gold_luxe", "coral" to "coral_reef", "copper" to "copper_dusk", "rose" to "sakura_bloom",
        "teal" to "ocean_teal", "mint" to "mint_frost", "lavender" to "lavender_haze", "glacier" to "glacier_blue",
        "lime" to "toxic_lime", "pearl" to "pearl_champagne", "blush" to "blush_quartz", "sky" to "sky_porcelain",
    )
    /** Seeds of v2.11 / pre-2.11 presets (accent_seed was the only pref before v2.11) → their v2.12 preset key. */
    private val LEGACY_SEEDS: Map<Int, String> = mapOf(
        0xFF8AB4FF.toInt() to "obsidian_noir", 0xFF4C6FFF.toInt() to "sapphire_depths", 0xFFA855F7.toInt() to "violet_nebula",
        0xFFE53950.toInt() to "crimson_eclipse", 0xFF6F7FA0.toInt() to "arctic_silver", 0xFF3B82F6.toInt() to "aurora_glass",
        0xFF8B6CFF.toInt() to "amethyst_night", 0xFF2F7DF6.toInt() to "sapphire_depths", 0xFFD0103A.toInt() to "ruby_noir",
        0xFF5B5BD6.toInt() to "royal_indigo", 0xFF06B6D4.toInt() to "cyber_cyan", 0xFF2EAD5B.toInt() to "emerald_aura",
        0xFFFF7A2F.toInt() to "sunset_ember", 0xFFF2B705.toInt() to "golden_eclipse", 0xFFD4917F.toInt() to "rose_gold_luxe",
        0xFFFF6F61.toInt() to "coral_reef", 0xFFC2703D.toInt() to "copper_dusk", 0xFFF0609E.toInt() to "sakura_bloom",
        0xFF00A896.toInt() to "ocean_teal", 0xFF3DDC97.toInt() to "mint_frost", 0xFFB39DDB.toInt() to "lavender_haze",
        0xFF8FB8DE.toInt() to "glacier_blue", 0xFF8BC34A.toInt() to "toxic_lime", 0xFFA79B8E.toInt() to "pearl_champagne",
        0xFFE8A0BF.toInt() to "blush_quartz", 0xFF5AA9E6.toInt() to "sky_porcelain",
    )
    /** A v2.12 key for any key ever saved (new keys pass through). */
    fun migrateKey(key: String?): String? = if (key.isNullOrEmpty()) key else LEGACY[key] ?: key
    private const val KEY_SEED = "accent_seed"
    private const val KEY_CUSTOM = "custom_themes"
    private const val KEY_VERSION = "theme_version"
    // v2.11 (new keys only; older keys are untouched)
    private const val KEY_THEME = "theme_key"          // preset key, "custom" or "custom:<id>"
    private const val KEY_SECONDARY = "theme_secondary" // custom: secondary accent seed (0 = auto)
    private const val KEY_BASE = "theme_base"           // custom: preset key whose background/glass is used ("" = auto)

    /** True when this phone can build a palette from any color (Android 12+). */
    val exactCustomColors: Boolean get() = Build.VERSION.SDK_INT >= 31 && DynamicColors.isDynamicColorAvailable()

    fun seed(c: Context): Int = Prefs.sp(c).getInt(KEY_SEED, DEFAULT_SEED)
    fun version(c: Context): Int = Prefs.sp(c).getInt(KEY_VERSION, 0)

    /** What the app is drawn with now. Exactly one of [preset] / custom ([seed] + optional extras). */
    data class Selection(val preset: Preset?, val seed: Int, val secondary: Int, val base: String, val customId: String?) {
        val isCustom get() = preset == null
    }

    fun selection(c: Context): Selection {
        val sp = Prefs.sp(c)
        val key = sp.getString(KEY_THEME, null)
        val seed = seed(c)
        val sec = sp.getInt(KEY_SECONDARY, 0)
        val base = migrateKey(sp.getString(KEY_BASE, "") ?: "") ?: ""
        if (key != null && !key.startsWith("custom")) presetByKey(migrateKey(key))?.let { return Selection(it, it.seed, 0, "", null) }
        if (key == null || (sec == 0 && base.isEmpty())) {
            // Pre-2.11 installs only have accent_seed: a preset seed keeps that preset, anything else is a custom color.
            presetFor(seed)?.let { return Selection(it, it.seed, 0, "", null) }
            if (key == null) presetByKey(LEGACY_SEEDS[seed or 0xFF000000.toInt()])?.let { return Selection(it, it.seed, 0, "", null) }
        }
        return Selection(null, seed, sec, base, key?.substringAfter("custom:", "")?.ifEmpty { null })
    }

    fun setPreset(c: Context, p: Preset) {
        Prefs.sp(c).edit().putString(KEY_THEME, p.key).putInt(KEY_SEED, p.seed or 0xFF000000.toInt())
            .remove(KEY_SECONDARY).remove(KEY_BASE).putInt(KEY_VERSION, version(c) + 1).apply()
    }

    /** Applies a custom color theme (optionally a saved one, by [id]). */
    fun setCustom(c: Context, seed: Int, secondary: Int = 0, base: String = "", id: String? = null) {
        Prefs.sp(c).edit().putString(KEY_THEME, if (id != null) "custom:$id" else "custom")
            .putInt(KEY_SEED, seed or 0xFF000000.toInt()).putInt(KEY_SECONDARY, if (secondary == 0) 0 else secondary or 0xFF000000.toInt())
            .putString(KEY_BASE, base).putInt(KEY_VERSION, version(c) + 1).apply()
    }

    /** Kept for older callers: a preset seed selects that preset, anything else becomes a custom color. */
    fun setSeed(c: Context, seed: Int) { presetFor(seed)?.let { setPreset(c, it) } ?: setCustom(c, seed) }

    fun resetToDefault(c: Context) { presetByKey(DEFAULT_KEY)?.let { setPreset(c, it) } }

    /** Bumps the version so open screens recreate themselves (used when light/dark mode changes too). */
    fun touch(c: Context) = Prefs.sp(c).edit().putInt(KEY_VERSION, version(c) + 1).apply()

    fun presetByKey(key: String?): Preset? = if (key.isNullOrEmpty()) null else presets.firstOrNull { it.key == key }
    fun presetFor(seed: Int): Preset? = presets.firstOrNull { (it.seed or 0xFF000000.toInt()) == (seed or 0xFF000000.toInt()) }

    /** Closest preset by hue, saturation and brightness (used on Android 11 and older for custom colors). */
    fun nearestPreset(seed: Int): Preset {
        val a = FloatArray(3); Color.colorToHSV(seed, a)
        return presets.filter { it.key != DEFAULT_KEY }.minByOrNull { p ->
            val b = FloatArray(3); Color.colorToHSV(p.seed, b)
            val dh = Math.abs(a[0] - b[0]).let { if (it > 180) 360 - it else it } / 180f
            // Grey-ish colors match the silver/pearl themes; hue matters less when saturation is low.
            val satW = (a[1] + b[1]) / 2f
            dh * dh * 4f * satW + (a[1] - b[1]) * (a[1] - b[1]) + (a[2] - b[2]) * (a[2] - b[2]) * 0.5f
        } ?: presets[0]
    }

    /** Applies the theme to an activity. Call in onCreate before setContentView. */
    fun apply(activity: Activity, player: Boolean = false) {
        val sel = selection(activity)
        val t = activity.theme
        val p = sel.preset
        if (p != null) { t.applyStyle(if (player) p.playerStyle else p.style, true); return }
        val near = nearestPreset(sel.seed)
        val base = presetByKey(sel.base)
        t.applyStyle(if (player) near.playerStyle else near.style, true)
        if (exactCustomColors) {
            DynamicColors.applyToActivityIfAvailable(activity, DynamicColorsOptions.Builder().setContentBasedSource(sel.seed).build())
            // Dynamic colors also replace the surfaces with Material's neutral greys: put the glass background back.
            val g = base ?: near
            t.applyStyle(if (player) g.glassPlayerStyle else g.glassStyle, true)
        } else if (base != null) {
            t.applyStyle(if (player) base.glassPlayerStyle else base.glassStyle, true)
        }
        if (sel.secondary != 0) nearestPreset(sel.secondary).let { s -> t.applyStyle(if (player) s.secondPlayerStyle else s.secondStyle, true) }
    }

    // ---- palettes for previews (theme gallery cards and the live preview) ----
    data class Palette(
        val bg: Int, val surface: Int, val glass: Int, val glassStrong: Int, val stroke: Int, val highlight: Int,
        val primary: Int, val onPrimary: Int, val primaryContainer: Int, val onPrimaryContainer: Int,
        val secondary: Int, val tertiary: Int, val text: Int, val textDim: Int,
        // v2.12: atmosphere, level-2 glass and pill navigation
        val atmoTop: Int = bg, val atmoMid: Int = bg, val atmoBottom: Int = bg, val glowA: Int = 0, val glowB: Int = 0,
        val elevated: Int = glass, val navContainer: Int = glassStrong, val navSelected: Int = text, val navOnSelected: Int = bg,
        val navText: Int = textDim,
    )

    private val paletteAttrs = intArrayOf(
        android.R.attr.colorBackground,
        com.google.android.material.R.attr.colorSurfaceContainerHigh,
        R.attr.glassSurface, R.attr.glassSurfaceStrong, R.attr.glassStroke, R.attr.glassHighlight,
        androidx.appcompat.R.attr.colorPrimary, com.google.android.material.R.attr.colorOnPrimary,
        com.google.android.material.R.attr.colorPrimaryContainer, com.google.android.material.R.attr.colorOnPrimaryContainer,
        com.google.android.material.R.attr.colorSecondary, com.google.android.material.R.attr.colorTertiary,
        com.google.android.material.R.attr.colorOnSurface, com.google.android.material.R.attr.colorOnSurfaceVariant,
        R.attr.atmoTop, R.attr.atmoMid, R.attr.atmoBottom, R.attr.atmoGlowA, R.attr.atmoGlowB,
        R.attr.glassSurfaceElevated, R.attr.navContainer, R.attr.navSelected, R.attr.navOnSelected, R.attr.navText,
    )

    /** The real colors a preset draws with in the current light/dark mode (read from its generated overlay). */
    fun palette(c: Context, p: Preset): Palette {
        val w = android.view.ContextThemeWrapper(c, R.style.Theme_Vela)
        w.theme.applyStyle(p.style, true)
        // obtainStyledAttributes expects the attributes in ascending order.
        val order = paletteAttrs.indices.sortedBy { paletteAttrs[it] }
        val asc = order.map { paletteAttrs[it] }.toIntArray()
        val a = w.obtainStyledAttributes(asc)
        val v = IntArray(paletteAttrs.size)
        order.forEachIndexed { idx, orig -> v[orig] = a.getColor(idx, 0) }
        a.recycle()
        return Palette(v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7], v[8], v[9], v[10], v[11], v[12], v[13],
            v[14], v[15], v[16], v[17], v[18], v[19], v[20], v[21], v[22], v[23])
    }

    /**
     * Palette for a custom color: glass/background from [base] (or the nearest preset), accent roles generated from
     * [seed] exactly like the app will (Material "content" scheme on Android 12+, nearest preset on 11 and older),
     * and an optional [secondary] accent.
     */
    fun customPalette(c: Context, seed: Int, secondary: Int = 0, base: String = "", night: Boolean): Palette {
        val near = nearestPreset(seed)
        val glass = palette(c, presetByKey(base) ?: near)
        var out = if (exactCustomColors) {
            val sch = com.google.android.material.color.utilities.SchemeContent(com.google.android.material.color.utilities.Hct.fromInt(seed), night, 0.0)
            val m = com.google.android.material.color.utilities.MaterialDynamicColors()
            glass.copy(
                primary = m.primary().getArgb(sch), onPrimary = m.onPrimary().getArgb(sch),
                primaryContainer = m.primaryContainer().getArgb(sch), onPrimaryContainer = m.onPrimaryContainer().getArgb(sch),
                secondary = m.secondary().getArgb(sch), tertiary = m.tertiary().getArgb(sch),
            )
        } else {
            val n = palette(c, near)
            glass.copy(primary = n.primary, onPrimary = n.onPrimary, primaryContainer = n.primaryContainer,
                onPrimaryContainer = n.onPrimaryContainer, secondary = n.secondary, tertiary = n.tertiary)
        }
        if (secondary != 0) { val s = palette(c, nearestPreset(secondary)); out = out.copy(secondary = s.secondary, tertiary = s.tertiary) }
        // v2.12: one colour → its own atmosphere (unless a base theme was chosen in Advanced).
        if (presetByKey(base) == null) {
            val a = Atmosphere.fromSeed(seed, secondary, night)
            out = out.copy(atmoTop = a.top, atmoMid = a.mid, atmoBottom = a.bottom, glowA = a.glowA, glowB = a.glowB, bg = a.mid)
        }
        return out
    }

    // ---- saved custom themes (JSON in prefs; pre-2.11 entries were {name, seed}) ----
    data class Custom(val id: String, val name: String, val seed: Int, val secondary: Int = 0, val base: String = "")

    fun customThemes(c: Context): List<Custom> = try {
        val a = JSONArray(Prefs.sp(c).getString(KEY_CUSTOM, "[]"))
        (0 until a.length()).map {
            val o = a.getJSONObject(it)
            val seed = o.getInt("seed")
            Custom(o.optString("id").ifEmpty { "s" + Integer.toHexString(seed) }, o.getString("name"), seed,
                o.optInt("secondary", 0), migrateKey(o.optString("base", "")) ?: "")
        }
    } catch (_: Exception) { emptyList() }

    /** Adds a new saved theme, or replaces the one with the same [Custom.id]. Returns it. */
    fun saveCustom(c: Context, t: Custom): Custom {
        val list = customThemes(c).toMutableList()
        val i = list.indexOfFirst { it.id == t.id }
        val fixed = t.copy(seed = t.seed or 0xFF000000.toInt())
        if (i >= 0) list[i] = fixed else list.add(0, fixed)
        writeCustom(c, list.take(40))
        return fixed
    }
    fun saveCustom(c: Context, name: String, seed: Int) = saveCustom(c, Custom(newId(), name, seed))
    fun newId() = java.lang.Long.toString(System.currentTimeMillis(), 36)
    fun deleteCustom(c: Context, id: String) = writeCustom(c, customThemes(c).filter { it.id != id })
    private fun writeCustom(c: Context, l: List<Custom>) {
        val a = JSONArray()
        l.forEach { a.put(JSONObject().put("id", it.id).put("name", it.name).put("seed", it.seed).put("secondary", it.secondary).put("base", it.base)) }
        Prefs.sp(c).edit().putString(KEY_CUSTOM, a.toString()).apply()
    }

    fun hex(color: Int) = String.format("#%06X", color and 0xFFFFFF)
    fun parseHex(s: String): Int? {
        val t = s.trim().removePrefix("#")
        val full = when (t.length) { 3 -> t.map { "$it$it" }.joinToString(""); 6 -> t; else -> return null }
        return full.toLongOrNull(16)?.let { (0xFF000000 or it).toInt() }
    }

    /** Reads a theme color attribute (e.g. colorPrimary) from any themed context. */
    fun attr(c: Context, attr: Int): Int {
        val tv = android.util.TypedValue()
        return if (c.theme.resolveAttribute(attr, tv, true)) {
            if (tv.resourceId != 0) androidx.core.content.ContextCompat.getColor(c, tv.resourceId) else tv.data
        } else DEFAULT_SEED
    }
    fun primary(c: Context) = attr(c, androidx.appcompat.R.attr.colorPrimary)
    /** Like [attr] but with an explicit fallback when the theme does not define it. */
    fun attrOr(c: Context, attr: Int, fallback: Int): Int {
        val tv = android.util.TypedValue()
        return if (c.theme.resolveAttribute(attr, tv, true)) {
            if (tv.resourceId != 0) androidx.core.content.ContextCompat.getColor(c, tv.resourceId) else tv.data
        } else fallback
    }

    /** True when the activity is currently drawn with the light (day) palette. */
    fun isLight(a: Activity): Boolean {
        val tv = android.util.TypedValue()
        if (a.theme.resolveAttribute(androidx.appcompat.R.attr.isLightTheme, tv, true)) return tv.data != 0
        val night = a.resources.configuration.uiMode and android.content.res.Configuration.UI_MODE_NIGHT_MASK
        return night != android.content.res.Configuration.UI_MODE_NIGHT_YES
    }

    /**
     * Status bar that stays readable: the theme's surface color behind it, dark icons on the light theme and
     * light icons on the dark theme. Light/Dark/System changes recreate the activity, so this re-runs then.
     * The navigation bar is left as the system/theme draws it.
     */
    @Suppress("DEPRECATION")
    fun styleStatusBar(a: Activity) {
        val w = a.window ?: return
        val light = isLight(a)
        // v2.12: the bar is transparent so the atmosphere runs behind it (set in Atmosphere.applyTo).
        // Before Android 6 icons are always white, so keep a dark bar there in light mode.
        w.statusBarColor = if (light && Build.VERSION.SDK_INT < 23) 0xFF000000.toInt() else android.graphics.Color.TRANSPARENT
        androidx.core.view.WindowCompat.getInsetsController(w, w.decorView).isAppearanceLightStatusBars = light && Build.VERSION.SDK_INT >= 23
    }
}

/** Base for screens that follow the theme: applies it, and recreates when it changes elsewhere. */
abstract class ThemedActivity : androidx.appcompat.app.AppCompatActivity() {
    private var themeVersion = -1
    private var backdropVersion = -1
    protected open val isPlayerTheme = false
    /**
     * Screens that manage the system bars themselves (fullscreen / immersive, like the player) return false
     * so the status-bar styling below never fights them.
     */
    protected open val styleSystemBars = true
    override fun onCreate(savedInstanceState: android.os.Bundle?) {
        ThemeManager.apply(this, isPlayerTheme)
        themeVersion = ThemeManager.version(this)
        backdropVersion = Backdrop.version(this)
        super.onCreate(savedInstanceState)
        if (!isPlayerTheme) Atmosphere.applyTo(this)
        if (styleSystemBars && !isPlayerTheme) ThemeManager.styleStatusBar(this)
    }
    override fun onResume() {
        super.onResume()
        if (themeVersion != ThemeManager.version(this)) { themeVersion = ThemeManager.version(this); recreate(); return }
        // v2.18.2: background photo changed on another screen -> refresh it IN PLACE (no recreate: recreating restored
        // Settings' hidden back-stack screens and left the main list stuck when the user came back).
        if (!isPlayerTheme && backdropVersion != Backdrop.version(this)) { backdropVersion = Backdrop.version(this); Atmosphere.refresh(this) }
    }
    /**
     * v2.19: a popup menu / overflow / dropdown just took focus from this screen: give it the Android 12+ blur behind
     * (or the opaque fallback when the system has blur off). Theme-level, so no call site changes; never the player.
     */
    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)
        if (!hasFocus && !isPlayerTheme && android.os.Build.VERSION.SDK_INT >= 31) {
            Glass.blurPopupWindows(this)
            window.decorView.post { if (!isFinishing) Glass.blurPopupWindows(this) }
        }
    }
    /** v2.18: a screen that just changed the backdrop itself re-applies it live instead of recreating. */
    protected fun backdropChangedHere() { backdropVersion = Backdrop.version(this); Atmosphere.refresh(this) }
}
